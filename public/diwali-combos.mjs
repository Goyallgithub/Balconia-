export function matchesComboFilter(c,filter){
 return filter==='all'||filter==='lights-only'&&c.kind==='lights-only'||filter==='plants-lights'&&c.kind!=='lights-only'||filter==='hanging'&&c.lines.some(x=>x.product?.category==='plants'&&/hanging/i.test(x.product.name))||filter==='2500'&&c.totalPaise<250000||filter==='2800'&&c.totalPaise<280000;
}
export function resolveCombo(combo,products){
 const lines=combo.items.map(([id,quantity])=>({product:products.find(p=>p.id===id),quantity}));
 const valid=lines.length>0&&lines.every(({product:p,quantity})=>p&&!p.planterOnly&&(combo.kind==='lights-only'?p.category==='lights':['plants','lights'].includes(p.category))&&Number.isInteger(p.pricePaise)&&p.pricePaise>0&&Number.isInteger(quantity)&&quantity>0);
 const totalPaise=valid?lines.reduce((sum,x)=>sum+x.product.pricePaise*x.quantity,0):null;
 return {...combo,lines,totalPaise,available:valid&&totalPaise<300000};
}
export function addComboToCart(cart,combo){
 if(!combo.available)throw Error('This combo is currently unavailable. Please explore another combination.');
 const next=cart.map(x=>({...x}));
 for(const {product,quantity} of combo.lines){const current=next.find(x=>x.id===product.id);if((current?.quantity||0)+quantity>20)throw Error('Your bag would exceed 20 of one product. Please adjust its quantity first.');if(current)current.quantity+=quantity;else next.push({id:product.id,quantity});}
 if(next.length>40)throw Error('Your bag can hold up to 40 different products. Please adjust your bag first.');
 return next;
}
